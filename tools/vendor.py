# Lucide icons (ISC). Only these are kept, as one ES module (/vendor/lucide/icons.js: name -> inner SVG markup).
# tests/test_icons.py checks that every icon("...") the front end asks for is in this list.
LUCIDE = ("lucide-static", "1.71.0")
ICONS = sorted({
    "arrow-up", "book", "book-open", "chart-no-axes-column", "check", "chevron-left", "chevron-right", "circle-alert",
    "clock", "copy", "download", "ellipsis", "external-link", "file-text", "flask-conical", "graduation-cap", "key-round",
    "library-big", "link", "list", "lock", "log-in", "log-out", "menu", "message-circle", "message-circle-question",
    "mic", "moon", "newspaper", "notebook-pen", "paperclip", "pencil", "play", "plus", "podcast", "refresh-cw",
    "scroll-text", "search", "settings", "sliders-horizontal", "sparkles", "sun", "sun-moon", "trash-2", "undo-2",
    "user-check", "user-x", "users", "video", "x",
})


def get(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": "knwlge-build"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def fetch(name: str, version: str) -> bytes:
    """The package tarball, checked against the registry's published sha512."""
    meta = json.loads(get(f"https://registry.npmjs.org/{name}/{version}"))
    tarball, integrity = meta["dist"]["tarball"], meta["dist"]["integrity"]
    data = get(tarball)
    algo, want = integrity.split("-", 1)
    assert algo == "sha512", integrity
    got = base64.b64encode(hashlib.sha512(data).digest()).decode()
    if got != want:
        sys.exit(f"{name}: integrity mismatch")
    return data


def icons(out: Path) -> None:
    name, version = LUCIDE
    with tarfile.open(fileobj=io.BytesIO(fetch(name, version))) as tf:
        members = {m.name.removeprefix("package/"): m for m in tf.getmembers() if m.isfile()}
        found = {}
        for icon in ICONS:
            m = members.get(f"icons/{icon}.svg")
            if m is None:
                sys.exit(f"{name}: no icon called {icon}")
            svg = tf.extractfile(m).read().decode()
            inner = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S).group(1)
            found[icon] = " ".join(inner.split())
        licence = tf.extractfile(members["LICENSE"]).read()
    (out / "lucide").mkdir(parents=True, exist_ok=True)
    (out / "lucide" / "icons.js").write_text(f"// Lucide {version} (ISC licence: LICENSE beside this file). Generated by tools/vendor.py.\n"
                                             f"export default {json.dumps(found, indent=0)};\n")
    (out / "lucide" / "LICENSE").write_bytes(licence)
    print(f"{name} {version} ok ({len(found)} icons)")


def main(out: Path) -> None:
    icons(out)
    for name, (version, files) in PACKAGES.items():
        data = fetch(name, version)
        with tarfile.open(fileobj=io.BytesIO(data)) as tf:
            members = {m.name.removeprefix("package/"): m for m in tf.getmembers() if m.isfile()}
            for src, dest in files.items():
                if isinstance(src, str) and src.endswith("/"):
                    hits = [k for k in members if k.startswith(src)]
                    if not hits:
                        sys.exit(f"{name}: nothing under {src}")
                    for k in hits:
                        rel = k[len(src):]
                        if ".." in Path(rel).parts:
                            continue
                        target = out / dest / rel
                        target.parent.mkdir(parents=True, exist_ok=True)
                        target.write_bytes(tf.extractfile(members[k]).read())
                    continue
                found = next((c for c in src if c in members), None)
                if not found:
                    sys.exit(f"{name}: none of {src} in package")
                target = out / dest
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_bytes(tf.extractfile(members[found]).read())
        print(f"{name} {version} ok")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
